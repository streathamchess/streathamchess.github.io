"""Record the pixel size of every local image the site uses, in _data/image_sizes.yml.

The page layout reads that file to add width/height attributes to <img> tags (stops the page jumping while
images load). Jekyll on GitHub Pages cannot read image sizes itself, so run this after adding or changing images:

    1. build the site:            bundle exec jekyll build
    2. from the repo root, run:   python _tools/image_sizes.py            (needs: pip install pillow)
    3. commit _data/image_sizes.yml

An image that is missing from the file still works; it just gets no width/height.
"""

import html
import json
import re
import sys
import urllib.parse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SITE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "_site"

sources = set()
for page in SITE.rglob("*.html"):
    text = page.read_text(encoding="utf-8", errors="ignore")
    for tag in re.findall(r"<img\b[^>]*>", text, flags=re.I):
        m = re.search(r"""\bsrc=(?:"([^"]*)"|'([^']*)')""", tag)
        if m:
            src = m.group(1) or m.group(2)
            if src.startswith("/") and not src.startswith("//"):
                sources.add(src)

sizes = {}
for src in sorted(sources):
    real = ROOT / urllib.parse.unquote(html.unescape(src)).lstrip("/").strip()
    if real.is_file():
        try:
            with Image.open(real) as im:
                sizes[src] = list(im.size)
        except OSError:
            pass

out = ROOT / "_data" / "image_sizes.yml"
out.parent.mkdir(exist_ok=True)
lines = ["# Generated by _tools/image_sizes.py - do not edit by hand. Image URL as written in the page: [width, height]."]
lines += [f"{json.dumps(src)}: [{w}, {h}]" for src, (w, h) in sizes.items()]
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(sizes)} of {len(sources)} image URLs recorded in {out.relative_to(ROOT)}")
